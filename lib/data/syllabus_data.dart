### 🔑 ભારતીય રાજ્યનું સ્વરૂપ - ૫ મુખ્ય શબ્દોનો સાચો ક્રમ (પરીક્ષામાં વારંવાર પૂછાતો પ્રશ્ન)
સૂત્ર: **SO - SO - SE - DE - RE**
1. **સંપૂર્ણ પ્રભુત્વ-સંપન્ન / સાર્વભૌમ (Sovereign):** ભારત કોઈપણ બાહ્ય સત્તા કે વિદેશી નિયંત્રણને આધીન નથી. ભારત પોતાના તમામ આંતરિક અને બાહ્ય નિર્ણયો લેવા સંપૂર્ણ સ્વતંત્ર છે.
2. **સમાજવાદી (Socialist):** ૪૨મા સુધારા ૧૯૭૬ દ્વારા ઉમેરાયો. ભારતનો સમાજવાદ એ માર્ક્સવાદી સામ્યવાદ નથી પરંતુ **લોકતાંત્રિક સમાજવાદ (Democratic Socialism)** છે, જેમાં મિશ્ર અર્થતંત્ર સ્વીકારાયું છે (ગાંધીવાદ તરફ વિશેષ ઝુકાવ).
3. **પંથનિરપેક્ષ / બિનસાંપ્રદાયિક (Secular):** ૪૨મા સુધારા ૧૯૭૬ દ્વારા ઉમેરાયો. ભારતીય રાજ્યનો કોઈ સત્તાવાર રાજ્યધર્મ નથી. રાજ્ય તમામ ધર્મોનું સમાન રક્ષણ કરે છે (સર્વધર્મ સમભાવ - Positive Secularism).
4. **લોકતંત્રાત્મક / લોકશાહી (Democratic):** સત્તા જનતાના હાથમાં છે અને સરકાર લોકો દ્વારા પુખ્ત વય મતાધિકારથી ચૂંટાય છે.
5. **ગણરાજ્ય / પ્રજાસત્તાક (Republic):** દેશના સર્વોચ્ચ વડા (રાષ્ટ્રપતિ) વંશપરંપરાગત (બ્રિટનના રાજાની જેમ) નથી, પરંતુ પ્રજા દ્વારા ચોક્કસ સમય માટે પરોક્ષ રીતે ચૂંટાય છે.

