### 🎯 બંધારણના મુખ્ય ઉદ્દેશો / લક્ષ્યો
* **ન્યાય (Justice) - ૩ પ્રકાર:** સામાજિક, આર્થિક અને રાજકીય ન્યાય (૧૯૧૭ ની રશિયન ક્રાંતિમાંથી પ્રેરિત).
* **સ્વતંત્રતા (Liberty) - ૫ પ્રકાર:** વિચાર, અભિવ્યક્તિ, વિશ્વાસ, ધર્મ અને ઉપાસનાની સ્વતંત્રતા (૧૭૮૯ ની ફ્રેન્ચ ક્રાંતિમાંથી પ્રેરિત).
* **સમાનતા (Equality) - ૨ પ્રકાર:** પ્રતિષ્ઠા (Status) અને તક (Opportunity) ની સમાનતા.
* **બંધુતા (Fraternity):** વ્યક્તિની ગરિમા અને રાષ્ટ્રની એકતા તથા અખંડિતતા સુનિશ્ચિત કરતી ભાઈચારાની ભાવના.

